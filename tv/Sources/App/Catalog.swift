extension HomeReason {
    /// Read at draw time, so a change of language relabels the rails. Short:
    /// what a row needs to add is said in `railSubtitle`.
    var railTitle: String {
        switch self {
        case .becauseYouWatched(let seed, _): t("row.becauseYouWatched", ["title": seed])
        case .tasteFacet(let leader, _): t("row.tasteFacet", ["title": leader])
        case .sagas: t("row.sagas")
        case .withActor(let name): t("row.withActor", ["name": name])
        case .byDirector(let name): t("row.byDirector", ["name": name])
        case .genreEra(let genre, let decade):
            t("row.genreEra", ["genre": genre, "decade": Format.decadeName(decade)])
        case .recentlyAdded: t("row.recentlyAdded")
        case .longAgo: t("row.longAgo")
        case .rediscovery: t("row.rediscovery")
        case .stepAside: t("row.stepAside")
        case .season(let window):
            switch window {
            case "oct": t("row.seasonOctober")
            case "dec": t("row.seasonHolidays")
            default: t("row.seasonSummer")
            }
        case .forgottenGem: t("row.forgottenGem")
        case .thread(let leader, _, _): t("row.thread", ["title": leader])
        case .mood(let key): t("mood.\(key)")
        case .onThisDay(let kind):
            switch kind {
            case .anniversary(let years): t("row.anniversary", ["years": String(years)])
            case .yearAgo: t("row.yearAgo")
            }
        case .retrospective(let name): t("row.retrospective", ["name": name])
        case .thisMonth(let month, _): t("row.thisMonth", ["month": Format.monthName(month)])
        case .cineClub: t("row.club")
        case .upNext: t("row.upNext")
        case .tonight: t("tonight.title")
        case .stageShows: t("row.stageShows")
        case .watchlist: t("row.watchlist")
        case .popular(let series): t(series ? "row.popularSeries" : "row.popularFilms")
        }
    }

    /// The precision a row's short title leaves out, set beside it in grey;
    /// empty where the title says it all.
    var railSubtitle: String {
        switch self {
        case .sagas: t("row.sub.sagas")
        case .recentlyAdded: t("row.sub.recentlyAdded")
        case .forgottenGem: t("row.sub.forgottenGem")
        case .thread(_, let done, let total): t("row.sub.thread", ["done": String(done), "total": String(total)])
        case .thisMonth(_, let leader): t("row.sub.thisMonth", ["title": leader])
        case .cineClub(let theme, _):
            switch theme {
            case .keyword(let word): word
            case .composer(let name): t("row.sub.clubComposer", ["name": name])
            case .writer(let name): t("row.sub.clubWriter", ["name": name])
            }
        default: ""
        }
    }
}

